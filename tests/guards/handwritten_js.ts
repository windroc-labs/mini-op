import type { Guard, Violation } from "../lib/guard.ts";
import { scanned } from "../lib/repo.ts";

// FR-70: JS is only what .github/jxa.ts builds into mini/js/ from mini/ts/; nothing is written by
// hand. That the build reproduces each file byte for byte is `npm run typecheck`'s check.
const HEADER = (name: string) =>
  `// Generated by .github/jxa.ts from mini/ts/${name}.ts; do not edit (npm run jxa:write).\n`;

export const guard: Guard = {
  name: "handwritten_js",
  check(view) {
    const found: Violation[] = [];
    for (const file of scanned(view)) {
      if (!/\.[cm]?js$/i.test(file)) continue;
      const name = /^mini\/js\/(.+)\.js$/.exec(file)?.[1];
      if (name === undefined && file.startsWith("mini/js/")) {
        found.push({
          file,
          line: 1,
          message: "mini/js/ holds only the .js files built from mini/ts/",
        });
      } else if (name === undefined) {
        found.push({ file, line: 1, message: "JS outside mini/js/; write TS (mini/ts/) instead" });
      } else if (!view.read(file).startsWith(HEADER(name))) {
        found.push({
          file,
          line: 1,
          message: `not built from mini/ts/${name}.ts (no generated header)`,
        });
      }
    }
    return found;
  },
};
