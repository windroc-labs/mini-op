import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { test } from "node:test";
import { REPO, Sandbox } from "../lib/sandbox.ts";

const JXA = path.join(REPO, ".github/jxa.ts");
const DTS = fs.readFileSync(path.join(REPO, "mini/ts/jxa.d.ts"), "utf8");
const OK = 'function run(argv: string[]): string {\n  delay(0.1);\n  return argv.join(" ");\n}\n';
const HEADER = (name: string) =>
  `// Generated by .github/jxa.ts from mini/ts/${name}.ts; do not edit (npm run jxa:write).\n`;

async function fixture(t: Parameters<typeof Sandbox.create>[0], files: Record<string, string>) {
  const sb = await Sandbox.create(t);
  const root = path.join(sb.dir, "fixture");
  for (const [file, text] of Object.entries({ "mini/ts/jxa.d.ts": DTS, ...files })) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), text);
  }
  const run = (...args: string[]) =>
    sb.run(["node", JXA, "--root", root, ...args], { timeoutMs: 30000 });
  const read = (file: string) => fs.readFileSync(path.join(root, file), "utf8");
  const exists = (file: string) => fs.existsSync(path.join(root, file));
  return { run, read, exists };
}

test("the repo's mini/js matches tsc output", async (t) => {
  const sb = await Sandbox.create(t);
  const r = await sb.run(["node", JXA], { timeoutMs: 30000 });
  assert.equal(r.code, 0, r.stdout + r.stderr);
  assert.equal(r.stderr, "");
});

test("every entry is a standalone script with run, and every mini/js file is generated", () => {
  const entries = fs.readdirSync(path.join(REPO, "mini/ts")).filter((f) => /^[^.]+\.ts$/.test(f));
  assert.ok(entries.length >= 6, entries.join(" "));
  for (const entry of entries) {
    const text = fs.readFileSync(path.join(REPO, "mini/ts", entry), "utf8");
    assert.match(text, /^function run\(argv: string\[\]\)/m, entry);
    assert.doesNotMatch(text, /^\s*(import|export)\b/m, entry);
  }
  for (const file of fs.readdirSync(path.join(REPO, "mini/js"))) {
    if (file === "page") continue;
    const text = fs.readFileSync(path.join(REPO, "mini/js", file), "utf8");
    assert.ok(text.startsWith(HEADER(file.replace(/\.js$/, ""))), file);
  }
});

test("--write builds each entry under its header; a clean check then passes", async (t) => {
  const f = await fixture(t, { "mini/ts/a.ts": OK, "mini/ts/b.ts": OK });
  const w = await f.run("--write");
  assert.equal(w.code, 0, w.stdout + w.stderr);
  const a = f.read("mini/js/a.js");
  assert.ok(a.startsWith(HEADER("a")), a);
  assert.match(a, /^function run\(argv\) \{$/m);
  assert.doesNotMatch(a, /string\[\]/);
  assert.ok(f.exists("mini/js/b.js"));
  const c = await f.run();
  assert.equal(c.code, 0, c.stdout + c.stderr);
});

test("a drifted, missing or source-less mini/js file fails the check; --write repairs it", async (t) => {
  const f = await fixture(t, {
    "mini/ts/a.ts": OK,
    "mini/ts/b.ts": OK,
    "mini/js/a.js": "function run() {}\n",
    "mini/js/old.js": "function run() {}\n",
  });
  const r = await f.run();
  assert.equal(r.code, 1);
  assert.equal(
    r.stderr,
    [
      "jxa: mini/js/a.js differs from tsc output; run npm run jxa:write",
      "jxa: mini/js/b.js is missing; run npm run jxa:write",
      "jxa: mini/js/old.js has no source mini/ts/old.ts",
      "",
    ].join("\n"),
  );
  assert.equal((await f.run("--write")).code, 0);
  assert.ok(!f.exists("mini/js/old.js"));
  assert.equal((await f.run()).code, 0);
});

test("directories and non-.js files in mini/js are left alone", async (t) => {
  const f = await fixture(t, {
    "mini/ts/a.ts": OK,
    "mini/js/sub/x.js": "function run() {}\n",
    "mini/js/.DS_Store": "x",
    "mini/js/old.js": "function run() {}\n",
  });
  const r = await f.run();
  assert.equal(r.code, 1);
  assert.equal(
    r.stderr,
    "jxa: mini/js/a.js is missing; run npm run jxa:write\njxa: mini/js/old.js has no source mini/ts/old.ts\n",
  );
  const w = await f.run("--write");
  assert.equal(w.code, 0, w.stdout + w.stderr);
  assert.ok(f.exists("mini/js/sub/x.js"));
  assert.ok(f.exists("mini/js/.DS_Store"));
  assert.ok(!f.exists("mini/js/old.js"));
  const c = await f.run();
  assert.equal(c.code, 0, c.stdout + c.stderr);
});

test("type errors, modules and entries without run fail and write nothing", async (t) => {
  const f = await fixture(t, {
    "mini/ts/a.ts":
      "function run(argv: string[]): string {\n  const unused = 1;\n  return argv[0];\n}\n",
    "mini/ts/b.ts": 'export {};\nfunction run(): string {\n  return "";\n}\n',
    "mini/ts/c.ts": "function go(): number {\n  return 1;\n}\ngo();\n",
    "mini/ts/d.ts": "function run(argv: string[]): number {\n  return argv;\n}\n",
  });
  const r = await f.run("--write");
  assert.equal(r.code, 1);
  assert.match(r.stderr, /^jxa: mini\/ts\/a\.ts\(2,9\): error TS6133: 'unused' is declared/m);
  assert.match(
    r.stderr,
    /^jxa: mini\/ts\/b\.ts: a JXA entry is a standalone script; no import or export$/m,
  );
  assert.match(r.stderr, /^jxa: mini\/ts\/c\.ts: no top-level function run$/m);
  assert.match(r.stderr, /^jxa: mini\/ts\/d\.ts\(2,3\): error TS2322/m);
  assert.ok(!f.exists("mini/js"));
});

test("entries see only the JXA globals, not node's", async (t) => {
  const f = await fixture(t, {
    "mini/ts/a.ts": "function run(): string {\n  return process.cwd();\n}\n",
  });
  const r = await f.run();
  assert.equal(r.code, 1);
  assert.match(r.stderr, /error TS\d+: Cannot find name 'process'/);
});

const PAGE =
  'function page(css: string): string {\n  // finds it\n  return document.querySelector(css)?.id ?? "";\n}\n';
const ONE = "a page program is one top-level function page and nothing else";

test("a page program builds to its parenthesised function under its header", async (t) => {
  const f = await fixture(t, { "mini/ts/a.ts": OK, "mini/ts/page/p.ts": PAGE });
  const w = await f.run("--write");
  assert.equal(w.code, 0, w.stdout + w.stderr);
  const text = f.read("mini/js/page/p.js");
  assert.ok(text.startsWith(HEADER("page/p")), text);
  const code = text.slice(HEADER("page/p").length);
  assert.match(code, /^\(function page\(css\) \{\n[\s\S]*\n\}\)\n$/);
  assert.doesNotMatch(code, /use strict|finds it|: string/);
  assert.equal((await f.run()).code, 0);
});

test("a page program is one function page, typed against the DOM only", async (t) => {
  const f = await fixture(t, {
    "mini/ts/page/a.ts": PAGE + 'page("x");\n',
    "mini/ts/page/b.ts": 'function go(): string {\n  return "";\n}\n',
    "mini/ts/page/c.ts": 'function page(): string {\n  return Application("x").name();\n}\n',
    "mini/ts/page/d.ts": 'export function page(): string {\n  return "";\n}\n',
  });
  const r = await f.run("--write");
  assert.equal(r.code, 1);
  for (const name of ["a", "b", "d"]) {
    assert.ok(r.stderr.includes(`jxa: mini/ts/page/${name}.ts: ${ONE}\n`), r.stderr);
  }
  assert.match(r.stderr, /^jxa: mini\/ts\/page\/c\.ts\(2,10\): error TS2304: .*'Application'/m);
  assert.ok(!f.exists("mini/js"));
});

test("a page js without its source fails the check; --write removes it", async (t) => {
  const f = await fixture(t, { "mini/ts/page/p.ts": PAGE, "mini/js/page/old.js": "x\n" });
  const r = await f.run();
  assert.equal(r.code, 1);
  assert.equal(
    r.stderr,
    [
      "jxa: mini/js/page/p.js is missing; run npm run jxa:write",
      "jxa: mini/js/page/old.js has no source mini/ts/page/old.ts",
      "",
    ].join("\n"),
  );
  assert.equal((await f.run("--write")).code, 0);
  assert.ok(!f.exists("mini/js/page/old.js"));
  assert.ok(f.exists("mini/js/page/p.js"));
});

test("unknown options and positionals are usage errors", async (t) => {
  const f = await fixture(t, { "mini/ts/a.ts": OK });
  for (const args of [["--bogus"], ["extra"]]) {
    const r = await f.run(...args);
    assert.equal(r.code, 2, args.join(" "));
    assert.match(r.stderr, /usage: jxa \[--root <dir>\] \[--write\]/);
  }
});
